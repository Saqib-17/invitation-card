-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.wedding_wishes (
  id bigint generated by default as identity primary key,
  guest_name text not null check (char_length(guest_name) between 1 and 80),
  message text not null check (char_length(message) between 1 and 1200),
  created_at timestamptz not null default now()
);
alter table public.wedding_wishes enable row level security;
-- Guests can submit wishes; public reads let the guestbook show new entries.
create policy "Anyone can submit wedding wishes"
on public.wedding_wishes for insert to anon, authenticated
with check (char_length(guest_name) between 1 and 80 and char_length(message) between 1 and 1200);
create policy "Anyone can view wedding wishes"
on public.wedding_wishes for select to anon, authenticated using (true);
-- Enable Realtime for live guestbook updates.
alter publication supabase_realtime add table public.wedding_wishes;
